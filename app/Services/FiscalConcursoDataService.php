    /**
     * Restaura os dados originais do catálogo mestre para um concurso específico.
     */
    public function resetToMaster(int $concursoId): ?FiscalConcurso
    {
        $concurso = FiscalConcurso::find($concursoId);
        if (!$concurso) {
            return null;
        }

        $catalog = $this->getMasterCatalog();
        $matchedItem = null;

        foreach ($catalog as $item) {
            if ($item['sigla'] === $concurso->sigla) {
                $matchedItem = $item;
                break;
            }
        }

        if (!$matchedItem) {
            return $concurso;
        }

        $matchedItem['editado_manualmente'] = false;
        $concurso->update($matchedItem);

        return $concurso->fresh();
    }

    /**
     * Busca concurso fiscal por termo livre (sigla, órgão, UF ou município).
     */
    public function search(string $query): ?FiscalConcurso
    {
        $clean = trim($query);
        if (empty($clean)) {
            return null;
        }

        // 1. Tentar busca exata por sigla
        $concurso = FiscalConcurso::whereRaw('LOWER(sigla) = ?', [strtolower($clean)])->first();
        if ($concurso) {
            return $concurso;
        }

        // 2. Tentar busca por UF direta (ex: "SP", "MG", "RJ")
        if (strlen($clean) === 2) {
            $concurso = FiscalConcurso::where('uf', strtoupper($clean))
                ->orderByRaw("CASE WHEN esfera = 'estadual' THEN 1 WHEN esfera = 'federal' THEN 2 ELSE 3 END")
                ->first();
            if ($concurso) {
                return $concurso;
            }
        }

        // 3. Tentar busca por termos compostos (ex: "sefaz sp", "iss bh", "receita federal")
        $termLower = strtolower($clean);
        return FiscalConcurso::whereRaw('LOWER(sigla) LIKE ?', ["%{$termLower}%"])
            ->orWhereRaw('LOWER(nome_orgao) LIKE ?', ["%{$termLower}%"])
            ->orWhereRaw('LOWER(municipio) LIKE ?', ["%{$termLower}%"])
            ->orWhereRaw('LOWER(cargo_principal) LIKE ?', ["%{$termLower}%"])
            ->first();
    }
